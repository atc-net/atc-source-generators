namespace Atc.SourceGenerators.Generators;

/// <summary>
/// Source generator for automatic enum-to-enum mapping with intelligent name matching and special case handling.
/// </summary>
[Generator]
public class EnumMappingGenerator : IIncrementalGenerator
{
    private const string AttributeNamespace = "Atc.SourceGenerators.Annotations";
    private const string AttributeMetadataName = "MapToAttribute";
    private const string FlagsAttributeMetadataName = "FlagsAttribute";
    private const string SystemNamespace = "System";

    private static readonly DiagnosticDescriptor TargetTypeMustBeEnumDescriptor = new(
        id: RuleIdentifierConstants.EnumMapping.TargetTypeMustBeEnum,
        title: "Target type must be an enum",
        messageFormat: "Target type '{0}' must be an enum type for enum mapping",
        category: RuleCategoryConstants.EnumMapping,
        DiagnosticSeverity.Error,
        isEnabledByDefault: true,
        helpLinkUri: DiagnosticHelpLink.For(RuleIdentifierConstants.EnumMapping.TargetTypeMustBeEnum));

    private static readonly DiagnosticDescriptor UnmappedEnumValueDescriptor = new(
        id: RuleIdentifierConstants.EnumMapping.UnmappedEnumValue,
        title: "Unmapped enum value",
        messageFormat: "Enum value '{0}.{1}' has no matching value in target enum '{2}'",
        category: RuleCategoryConstants.EnumMapping,
        DiagnosticSeverity.Warning,
        isEnabledByDefault: true,
        helpLinkUri: DiagnosticHelpLink.For(RuleIdentifierConstants.EnumMapping.UnmappedEnumValue));

    private static readonly DiagnosticDescriptor FlagEnumMappingWarningDescriptor = new(
        id: RuleIdentifierConstants.EnumMapping.FlagEnumMappingWarning,
        title: "Flag enum mapping warning",
        messageFormat: "Enum '{0}' has the [Flags] attribute and generated switch-based mapping may produce incorrect results for combined flag values",
        category: RuleCategoryConstants.EnumMapping,
        DiagnosticSeverity.Warning,
        isEnabledByDefault: true,
        helpLinkUri: DiagnosticHelpLink.For(RuleIdentifierConstants.EnumMapping.FlagEnumMappingWarning));

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // Note: MapToAttribute is generated by ObjectMappingGenerator in PostInitialization
        // Both generators share the same attribute, so it's only emitted once

        // Find enums with MapTo attribute and extract everything needed into equatable models
        // (no symbols), so an edit elsewhere reuses the cached models and output
        var enumMappings = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                $"{AttributeNamespace}.{AttributeMetadataName}",
                predicate: static (s, _) => s is EnumDeclarationSyntax,
                transform: static (ctx, ct) => ExtractMappingResult((INamedTypeSymbol)ctx.TargetSymbol, ct))
            .WithTrackingName("EnumMapping.Models")
            .Collect();

        // Generate source
        context.RegisterSourceOutput(enumMappings, static (spc, results) => Execute(results, spc));
    }

    private static void Execute(
        ImmutableArray<EnumMappingResult> results,
        SourceProductionContext context)
    {
        if (results.IsDefaultOrEmpty)
        {
            return;
        }

        var mappingsToGenerate = new List<EnumMappingInfo>();
        var seen = new HashSet<string>(StringComparer.Ordinal);

        foreach (var result in results)
        {
            context.CancellationToken.ThrowIfCancellationRequested();

            // Deduplicate (ForAttributeWithMetadataName emits once per declaration)
            if (!seen.Add(result.Key))
            {
                continue;
            }

            foreach (var diagnostic in result.Diagnostics)
            {
                context.ReportDiagnostic(diagnostic.ToDiagnostic());
            }

            mappingsToGenerate.AddRange(result.Mappings);
        }

        if (mappingsToGenerate.Count == 0)
        {
            return;
        }

        // Generate mapping extensions
        var source = GenerateMappingExtensions(mappingsToGenerate);
        context.AddSource("EnumMappingExtensions.g.cs", SourceText.From(source, Encoding.UTF8));
    }

    [SuppressMessage("Meziantou.Analyzer", "MA0051:Method is too long", Justification = "OK")]
    private static EnumMappingResult ExtractMappingResult(
        INamedTypeSymbol enumSymbol,
        CancellationToken cancellationToken)
    {
        var mappings = new List<EnumMappingInfo>();
        var diagnostics = new List<DiagnosticInfo>();

        // Get all MapTo attributes
        var attributes = enumSymbol
            .GetAttributes()
            .Where(a => IsAttributeMatch(a.AttributeClass, AttributeMetadataName, AttributeNamespace));

        foreach (var attribute in attributes)
        {
            cancellationToken.ThrowIfCancellationRequested();

            if (attribute.ConstructorArguments.Length == 0 ||
                attribute.ConstructorArguments[0].Value is not INamedTypeSymbol targetType)
            {
                continue;
            }

            // Validate target type is an enum
            if (targetType.TypeKind != TypeKind.Enum)
            {
                diagnostics.Add(DiagnosticInfo.Create(TargetTypeMustBeEnumDescriptor, enumSymbol, targetType.Name));
                continue;
            }

            // Warn if either enum has [Flags] attribute — switch expressions can't handle combined flag values
            if (HasFlagsAttribute(enumSymbol))
            {
                diagnostics.Add(DiagnosticInfo.Create(FlagEnumMappingWarningDescriptor, enumSymbol, enumSymbol.Name));
            }

            if (HasFlagsAttribute(targetType))
            {
                diagnostics.Add(DiagnosticInfo.Create(FlagEnumMappingWarningDescriptor, enumSymbol, targetType.Name));
            }

            // Extract Bidirectional property
            var bidirectional = attribute.NamedArguments
                .Where(namedArg => namedArg.Key == "Bidirectional")
                .Select(namedArg => namedArg.Value.Value as bool? ?? false)
                .FirstOrDefault();

            // Get enum value mappings
            var valueMappings = EnumMappingHelper.GetEnumValueMappings(enumSymbol, targetType);

            // Report warnings for unmapped values
            foreach (var mapping in valueMappings.Where(m => !m.IsMapped))
            {
                diagnostics.Add(DiagnosticInfo.Create(UnmappedEnumValueDescriptor, enumSymbol, enumSymbol.Name, mapping.SourceValue, targetType.Name));
            }

            var reverseValueMappings = bidirectional
                ? EnumMappingHelper.GetEnumValueMappings(sourceEnum: targetType, targetEnum: enumSymbol)
                : [];

            mappings.Add(new EnumMappingInfo(
                SourceEnumName: enumSymbol.ToGlobalDisplayString(),
                SourceEnumSimpleName: enumSymbol.Name,
                SourceNamespace: NamespaceHelper.GetNamespaceName(enumSymbol.ContainingNamespace),
                TargetEnumName: targetType.ToGlobalDisplayString(),
                TargetEnumSimpleName: targetType.Name,
                TargetNamespace: NamespaceHelper.GetNamespaceName(targetType.ContainingNamespace),
                ValueMappings: new EquatableArray<EnumMappingHelper.EnumValueMapping>(valueMappings),
                ReverseValueMappings: new EquatableArray<EnumMappingHelper.EnumValueMapping>(reverseValueMappings),
                Bidirectional: bidirectional));
        }

        return new EnumMappingResult(
            enumSymbol.ToDisplayString(),
            new EquatableArray<EnumMappingInfo>(mappings),
            new EquatableArray<DiagnosticInfo>(diagnostics));
    }

    private static string GenerateMappingExtensions(
        List<EnumMappingInfo> mappings)
    {
        var sb = new StringBuilder();
        var namespaces = new HashSet<string>(StringComparer.Ordinal);

        // Collect all namespaces (types in the global namespace need no using directive)
        foreach (var mapping in mappings)
        {
            if (mapping.SourceNamespace is not null)
            {
                namespaces.Add(mapping.SourceNamespace);
            }

            if (mapping.TargetNamespace is not null)
            {
                namespaces.Add(mapping.TargetNamespace);
            }
        }

        sb.AppendLineLf("// <auto-generated/>");
        sb.AppendLineLf("#nullable enable");
        sb.AppendLineLf();

        foreach (var ns in namespaces.OrderBy(x => x, StringComparer.Ordinal))
        {
            sb.AppendLineLf($"using {ns};");
        }

        sb.AppendLineLf();
        sb.AppendLineLf("namespace Atc.Mapping;");
        sb.AppendLineLf();
        sb.AppendLineLf("/// <summary>");
        sb.AppendLineLf("/// Extension methods for enum mapping.");
        sb.AppendLineLf("/// </summary>");
        sb.AppendLineLf("[global::System.CodeDom.Compiler.GeneratedCode(\"Atc.SourceGenerators.EnumMapping\", \"1.0.0\")]");
        sb.AppendLineLf("[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
        sb.AppendLineLf("[global::System.Runtime.CompilerServices.CompilerGenerated]");
        sb.AppendLineLf("[global::System.Diagnostics.DebuggerNonUserCode]");
        sb.AppendLineLf("[global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverage]");
        sb.AppendLineLf("public static class EnumMappingExtensions");
        sb.AppendLineLf("{");

        foreach (var mapping in mappings)
        {
            GenerateMappingMethod(sb, mapping.SourceEnumName, mapping.TargetEnumName, mapping.TargetEnumSimpleName, mapping.ValueMappings);

            // Generate reverse mapping if bidirectional
            if (mapping.Bidirectional)
            {
                GenerateMappingMethod(sb, mapping.TargetEnumName, mapping.SourceEnumName, mapping.SourceEnumSimpleName, mapping.ReverseValueMappings);
            }
        }

        sb.AppendLineLf("}");

        return sb.ToString();
    }

    private static bool HasFlagsAttribute(ITypeSymbol typeSymbol)
    {
        foreach (var attr in typeSymbol.GetAttributes())
        {
            if (IsAttributeMatch(attr.AttributeClass, FlagsAttributeMetadataName, SystemNamespace))
            {
                return true;
            }
        }

        return false;
    }

    private static bool IsAttributeMatch(
        INamedTypeSymbol? attributeClass,
        string expectedMetadataName,
        string expectedNamespace)
    {
        if (attributeClass is null)
        {
            return false;
        }

        return attributeClass.MetadataName == expectedMetadataName &&
               attributeClass.ContainingNamespace?.ToDisplayString() == expectedNamespace;
    }

    private static void GenerateMappingMethod(
        StringBuilder sb,
        string sourceEnumName,
        string targetEnumName,
        string targetEnumSimpleName,
        EquatableArray<EnumMappingHelper.EnumValueMapping> valueMappings)
    {
        var methodName = $"MapTo{TypeNameSanitizer.SanitizeForIdentifier(targetEnumSimpleName)}";

        sb.AppendLineLf("    /// <summary>");
        sb.AppendLineLf($"    /// Maps <see cref=\"{sourceEnumName}\"/> to <see cref=\"{targetEnumName}\"/>.");
        sb.AppendLineLf("    /// </summary>");
        sb.AppendLineLf($"    public static {targetEnumName} {methodName}(");
        sb.AppendLineLf($"        this {sourceEnumName} source)");
        sb.AppendLineLf("        => source switch");
        sb.AppendLineLf("        {");

        // Generate switch cases
        foreach (var valueMapping in valueMappings)
        {
            if (valueMapping.IsMapped &&
                valueMapping.TargetValue is not null)
            {
                sb.AppendLineLf($"            {sourceEnumName}.{CSharpIdentifier.Escape(valueMapping.SourceValue)} => {targetEnumName}.{CSharpIdentifier.Escape(valueMapping.TargetValue)},");
            }
        }

        sb.AppendLineLf("            _ => throw new global::System.ArgumentOutOfRangeException(nameof(source), source, \"Unmapped enum value\"),");
        sb.AppendLineLf("        };");
        sb.AppendLineLf();
    }
}